const scrollDescriptor = Object.getOwnPropertyDescriptor(HTMLElement.prototype, 'scrollIntoView')
beforeEach(() => {
  vi.stubGlobal('ResizeObserver', class { observe() {} unobserve() {} disconnect() {} })
  Object.defineProperty(HTMLElement.prototype, 'scrollIntoView', { configurable: true, value: vi.fn() })
})
afterEach(() => {
  cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals()
  if (scrollDescriptor) Object.defineProperty(HTMLElement.prototype, 'scrollIntoView', scrollDescriptor)
  else Reflect.deleteProperty(HTMLElement.prototype, 'scrollIntoView')
})

function navigate(label: string) {
  fireEvent.click(within(screen.getByRole('navigation', { name: '一级导航' })).getByRole('button', { name: label }))
}

function openUserMenuItem(label: string) {
  fireEvent.click(screen.getByRole('button', { name: 'Kakarrot 用户菜单' }))
  fireEvent.click(screen.getByRole('menuitem', { name: label }))
}

function openPersonalCenter() {
  openUserMenuItem('个人中心')
}

function selectCatalogAgent(name: string) {
  fireEvent.click(screen.getByRole('button', { name: `查看智能体 ${name}` }))
  fireEvent.click(within(screen.getByRole('dialog', { name: `${name}详情` })).getByRole('button', { name: '开始对话' }))
}

